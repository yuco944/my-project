  private buildPrompt(issue: IssueData, tasks: Task[]): string {
    return `You are a senior TypeScript developer. Generate production-ready code for the following issue.

Issue: ${issue.title}

Description:
${issue.body}

Tasks to implement:
${tasks.map((t, i) => `${i + 1}. ${t.description}`).join('\n')}

Requirements:
- Use TypeScript with strict mode
- Follow modern ES2022+ syntax
- Include proper error handling
- Add JSDoc comments
- Make code testable
- Use async/await for asynchronous operations

Please generate the necessary files with complete implementations.
Format your response as:

FILE: path/to/file.ts
\`\`\`typescript
// code here
\`\`\`

FILE: path/to/another-file.ts
\`\`\`typescript
// code here
\`\`\`
`;
  }

  private parseGeneratedCode(response: string, issue: IssueData): GeneratedCode {
    const files: Array<{ path: string; content: string }> = [];
    const fileMatches = response.matchAll(/FILE:\s*(.+?)\n```(?:typescript|ts)?\n([\s\S]+?)```/g);

    for (const match of fileMatches) {
      const path = match[1].trim();
      const content = match[2].trim();
      files.push({ path, content });
    }

    // If no files were parsed, create a default implementation file
    if (files.length === 0) {
      files.push({
        path: 'src/features/youtube-research.ts',
        content: `/**
 * ${issue.title}
 *
 * Auto-generated by CodeGenAgent
 */

export class YouTubeResearch {
  // TODO: Implement based on requirements
  constructor() {
    console.log('YouTubeResearch initialized');
  }
}
`,
      });
    }

    return {
      files,
      summary: `Generated ${files.length} file(s) for: ${issue.title}`,
    };
  }
